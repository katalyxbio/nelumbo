/**
 * Generates the Velvet theme from a seed color.
 *
 *   npm run theme                                   # neutral, blue brand
 *   npm run theme -- --brand green --neutral warm   # palette accent, warm grays
 *   npm run theme -- --brand "#0f766e" --vibrance 0.9
 *
 * Writes:
 *   src/styles/velvet.css   theme for the docs site
 *   registry.json           the "theme" item (cssVars + css) for `shadcn add`
 */
import { readFileSync, writeFileSync } from "node:fs"
import { buildScheme, schemeToCss, type Neutral } from "../src/lib/velvet/scheme"
import { cssTree, cssTreeToString, themeTokens } from "../src/lib/velvet/tokens"

const args = process.argv.slice(2)
const arg = (name: string) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 ? args[i + 1] : undefined
}
const brand = arg("brand") ?? "blue"
const neutral = (arg("neutral") ?? "pure") as Neutral
const vibrance = Number(arg("vibrance") ?? 1)
const radius = arg("radius") ?? "0.875rem"

const scheme = buildScheme({ brand, neutral, vibrance })

// ---- docs CSS --------------------------------------------------------------
const themeBlock = `@theme inline {\n${Object.entries(themeTokens)
  .map(([k, v]) => `  --${k}: ${v};`)
  .join("\n")}\n}`

const header = `/* Generated by scripts/build-theme.ts (brand ${brand}, neutral ${neutral}, vibrance ${vibrance}). Do not edit. */`
writeFileSync(
  "src/styles/velvet.css",
  [header, schemeToCss(scheme, { radius }), themeBlock, cssTreeToString(cssTree)].join("\n\n") + "\n"
)

// ---- registry item ---------------------------------------------------------
const registry = JSON.parse(readFileSync("registry.json", "utf8"))
const item = {
  name: "theme",
  type: "registry:theme",
  title: "Velvet Theme",
  description: `Velvet foundations: neutral color roles with an accent palette (brand ${brand}, ${neutral} neutrals), surfaces, elevation, spring motion, type roles and tactile utilities.`,
  dependencies: ["tw-animate-css"],
  cssVars: {
    theme: themeTokens,
    light: { radius, ...scheme.light },
    dark: scheme.dark,
  },
  css: cssTree,
}
registry.items = [item, ...registry.items.filter((i: { name: string }) => i.name !== "theme")]
writeFileSync("registry.json", JSON.stringify(registry, null, 2) + "\n")

console.log(`Velvet theme: ${neutral} neutrals, ${brand} brand, vibrance ${vibrance}.`)
