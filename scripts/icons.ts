/**
 * Collects every Material Symbols name used in src/ and registry/ and writes
 * src/lib/nelumbo/icons.generated.ts, which the layout turns into a subset
 * font URL. Runs before dev and build, so a new icon is never missing.
 *
 * Takes every string literal that is a real symbol name, wherever it appears
 * (attributes, ternaries, arrays, maps). That over-includes a few common words
 * that happen to be symbols ("link", "search"), at ~1 KB each, but it never
 * misses an icon. scripts/a11y.cjs checks the rendered pages for gaps.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const valid = new Set(
  [...readFileSync("node_modules/material-symbols/index.d.ts", "utf8").matchAll(/^\s+"([a-z0-9_]+)",?$/gm)].map((m) => m[1])
)

const files: string[] = []
const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(tsx?|mdx?)$/.test(p) && !p.endsWith(".generated.ts")) files.push(p)
  }
}
;["src", "registry"].forEach(walk)

const used = new Set<string>()
const re = /["'`]([a-z0-9_]+)["'`]/g
for (const f of files)
  for (const m of readFileSync(f, "utf8").matchAll(re)) if (valid.has(m[1])) used.add(m[1])

const list = [...used].sort()
writeFileSync(
  "src/lib/nelumbo/icons.generated.ts",
  `// Generated by scripts/icons.ts. Do not edit.\nimport type { IconName } from "@/registry/nelumbo/ui/icon"\n\nexport const USED_ICONS: IconName[] = ${JSON.stringify(list, null, 2)}\n`
)
console.log(`${list.length} Material Symbols in use.`)
